export function patchMapGraphemeBreakClass(codePoint: number): PatchMapGraphemeBreakClass {
  if (codePoint === 0x000d) return 'CR';
  if (codePoint === 0x000a) return 'LF';
  if (codePoint === 0x200d) return 'ZWJ';
  if (isControl(codePoint)) return 'Control';
  if (inRanges(codePoint, EXTEND_RANGES)) return 'Extend';
  if (inRanges(codePoint, SPACING_MARK_RANGES)) return 'SpacingMark';
  if (inRanges(codePoint, PREPEND_RANGES)) return 'Prepend';
  if (codePoint >= 0x1f1e6 && codePoint <= 0x1f1ff) return 'RegionalIndicator';
  if (codePoint >= 0x1100 && codePoint <= 0x115f) return 'L';
  if (codePoint >= 0xa960 && codePoint <= 0xa97c) return 'L';
  if (codePoint >= 0x1160 && codePoint <= 0x11a7) return 'V';
  if (codePoint >= 0xd7b0 && codePoint <= 0xd7c6) return 'V';
  if (codePoint >= 0x11a8 && codePoint <= 0x11ff) return 'T';
  if (codePoint >= 0xd7cb && codePoint <= 0xd7fb) return 'T';
  if (codePoint >= 0xac00 && codePoint <= 0xd7a3) {
    return (codePoint - 0xac00) % 28 === 0 ? 'LV' : 'LVT';
  }
  return 'Other';
}

export function patchMapIsExtendedPictographic(codePoint: number): boolean {
  return (
    codePoint === 0x00a9 ||
    codePoint === 0x00ae ||
    codePoint === 0x203c ||
    codePoint === 0x2049 ||
    (codePoint >= 0x2122 && codePoint <= 0x2139) ||
    (codePoint >= 0x2194 && codePoint <= 0x21ff) ||
    (codePoint >= 0x2300 && codePoint <= 0x23ff) ||
    (codePoint >= 0x2460 && codePoint <= 0x24ff) ||
    (codePoint >= 0x25a0 && codePoint <= 0x27ff) ||
    (codePoint >= 0x2b00 && codePoint <= 0x2bff) ||
    (codePoint >= 0x1f000 && codePoint <= 0x1faff)
  );
}

export function patchMapIsZeroAdvance(codePoint: number): boolean {
  return (
    codePoint === 0x200d ||
    codePoint === 0x200c ||
    (codePoint >= 0xfe00 && codePoint <= 0xfe0f) ||
    (codePoint >= 0xe0100 && codePoint <= 0xe01ef) ||
    (inRanges(codePoint, EXTEND_RANGES) && !(codePoint >= 0x1f3fb && codePoint <= 0x1f3ff))
  );
}

export function patchMapIsFullWidth(codePoint: number): boolean {
  return (
    (codePoint >= 0x1100 && codePoint <= 0x115f) ||
    codePoint === 0x2329 ||
    codePoint === 0x232a ||
    (codePoint >= 0x2e80 && codePoint <= 0xa4cf) ||
    (codePoint >= 0xac00 && codePoint <= 0xd7a3) ||
    (codePoint >= 0xf900 && codePoint <= 0xfaff) ||
    (codePoint >= 0xfe10 && codePoint <= 0xfe19) ||
    (codePoint >= 0xfe30 && codePoint <= 0xfe6f) ||
    (codePoint >= 0xff00 && codePoint <= 0xff60) ||
    (codePoint >= 0xffe0 && codePoint <= 0xffe6) ||
    codePoint > 0xffff
  );
}

export function patchMapIsRtlStrong(codePoint: number): boolean {
  return (
    (codePoint >= 0x0590 && codePoint <= 0x08ff) ||
    (codePoint >= 0xfb1d && codePoint <= 0xfdff) ||
    (codePoint >= 0xfe70 && codePoint <= 0xfeff) ||
    (codePoint >= 0x10800 && codePoint <= 0x10fff) ||
    (codePoint >= 0x1e800 && codePoint <= 0x1eeff)
  );
}

export function patchMapIsLtrStrong(codePoint: number): boolean {
  return (
    (codePoint >= 0x0041 && codePoint <= 0x005a) ||
    (codePoint >= 0x0061 && codePoint <= 0x007a) ||
    (codePoint >= 0x00c0 && codePoint <= 0x02ff) ||
    (codePoint >= 0x0370 && codePoint <= 0x058f) ||
    (codePoint >= 0x0900 && codePoint <= 0x1fff) ||
    (codePoint >= 0x2e80 && codePoint <= 0xd7ff) ||
    (codePoint >= 0xf900 && codePoint <= 0xfaff)
  );
}

export function patchMapIsHardBreak(cluster: string): boolean {
  return cluster === '\n' || cluster === '\r' || cluster === '\r\n';
}

function isControl(codePoint: number): boolean {
  return (
    (codePoint >= 0x0000 && codePoint <= 0x001f) ||
    (codePoint >= 0x007f && codePoint <= 0x009f) ||
    codePoint === 0x00ad ||
    codePoint === 0x061c ||
    codePoint === 0x180e ||
    (codePoint >= 0x200b && codePoint <= 0x200f) ||
    (codePoint >= 0x2028 && codePoint <= 0x202e) ||
    (codePoint >= 0x2060 && codePoint <= 0x206f) ||
    codePoint === 0xfeff
  );
}

function inRanges(codePoint: number, ranges: readonly Range[]): boolean {
  for (const [start, end] of ranges) {
    if (codePoint < start) return false;
    if (codePoint <= end) return true;
  }
  return false;
}
